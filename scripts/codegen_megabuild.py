def blend_equal(signals):
    """Equal-weight vote across strategy signal frames.

    Parameters
    ----------
    signals : list of pd.DataFrame
        Each with ``signal``/``confidence``/``gate`` columns.

    Returns
    -------
    pd.DataFrame with ``vote``, ``agreement`` and ``n`` columns.
    """
    if not signals:
        return pd.DataFrame(columns=["vote", "agreement", "n"])
    idx = signals[0].index
    votes = np.zeros(len(idx))
    conf_sum = np.zeros(len(idx))
    for s in signals:
        w = (s["confidence"].to_numpy(dtype=float) * s["gate"].to_numpy(dtype=float))
        votes = votes + np.sign(s["signal"].to_numpy(dtype=float)) * w
        conf_sum = conf_sum + w
    vote = votes / (conf_sum + 1e-12)
    n = float(len(signals))
    pos = np.zeros(len(idx))
    for s in signals:
        pos = pos + (np.sign(s["signal"].to_numpy(dtype=float)) > 0).astype(float)
    agreement = np.abs(pos / n - 0.5) * 2.0
