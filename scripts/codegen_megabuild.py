SHELL_PAT = Template('''

def $FUNC(df: pd.DataFrame, strict: bool = $STRICT) -> pd.DataFrame:
    """$TITLE.

    $DESC

    Parameters
    ----------
    df : pd.DataFrame
        Must contain ``open``/``high``/``low``/``close``.
    strict : bool
        Tighten geometric tolerances (fewer, cleaner hits).

    Returns
    -------
    pd.DataFrame
        Columns ``hit`` (0/1) and ``score`` (0..1 pattern quality).
    """
    for _c in ("open", "high", "low", "close"):
        if _c not in df.columns:
            raise ValueError("$FUNC requires columns open/high/low/close")
    o = df["open"].astype(float).to_numpy()
    h = df["high"].astype(float).to_numpy()
    l = df["low"].astype(float).to_numpy()
    c = df["close"].astype(float).to_numpy()
    n = len(df)
    body = np.abs(c - o) + 1e-12
    rng = (h - l) + 1e-12
    upper = h - np.maximum(c, o)
    lower = np.minimum(c, o) - l
$LOGIC
    hit = pd.Series(_hit.astype(float), index=df.index, name="hit")
    score = pd.Series(np.clip(_score, 0.0, 1.0), index=df.index, name="score")
    return pd.DataFrame({"hit": hit, "score": score}, index=df.index)
''')

PAT_PC1 = Template('''    _ratio = body / rng
    _tol = float($B1) if strict else float($B1) * 1.75
    _hit = _ratio < _tol
    _center = 1.0 - np.abs(upper - lower) / rng
    _score = np.clip((1.0 - _ratio / (_tol + 1e-12)) * 0.5 + _center * 0.5, 0.0, 1.0)''')

